package lomka.starl.mixins.net.minecraft.client.renderer.texture;

import com.mojang.blaze3d.platform.NativeImage;
import lomka.starl.duck.ISpriteContents;
import net.minecraft.client.renderer.texture.SpriteContents;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;
import org.spongepowered.asm.mixin.Unique;

/**
 * Drops the mip levels a sprite will never be re-uploaded from, keeping level 0.
 *
 * <p>{@code SpriteContents.byMipLevel} is a chain whose level 0 is the decoded image and whose
 * levels 1..N are generated by {@code MipmapGenerator}. Vanilla uploads every level once, during
 * {@code TextureAtlas.upload}, and then keeps the whole chain alive: the only reader afterwards is
 * an animated sprite's ticker, which re-uploads out of {@code byMipLevel} every frame.
 *
 * <p>Level 0 is deliberately kept. It is what {@code isTransparent} reads (and therefore what item
 * model generation and ambient occlusion read), it is what a debug atlas dump reads, and it is what
 * Axiom holds: {@code BlockColourComputation} takes {@code spriteContents.byMipLevel[0]} into a
 * task and reads its pixels from a runtime {@code getLab} call, long after the reload. Closing it
 * would be a native use-after-free, since {@code NativeImage.close()} is
 * {@code MemoryUtil.nmemFree}. Freeing only the generated levels sidesteps that by construction
 * rather than by ordering.
 */
@Mixin(SpriteContents.class)
public abstract class MixinSpriteContents implements ISpriteContents {

    @Shadow private NativeImage[] byMipLevel;

    /**
     * Frees every mip level above 0 and truncates the chain so the next {@code close()} does not
     * free them twice. No-op when mipmapping is off, which is the vanilla default: the chain then
     * has a single level.
     */
    @Override
    @Unique
    public void lomka$releaseUnusedMipLevels() {
        NativeImage[] mips = this.byMipLevel;
        if (mips == null || mips.length <= 1) {
            return;
        }

        // An animated sprite re-reads the chain from its ticker every frame, so it keeps all of it.
        // Above 1.21.9 that is asked directly; below it the question is answered through
        // getUniqueFrames(), which returns a single-element stream for a static sprite and two or
        // more entries for an animated one - SpriteContents#createAnimatedTexture returns null
        // whenever the frame list holds one entry or fewer, so the two cases cannot overlap.
        //? if >=1.21.9 {
        if (((SpriteContents) (Object) this).isAnimated()) {
            return;
        }
        //? } else {
        /*if (((SpriteContents) (Object) this).getUniqueFrames().count() > 1L) {
            return;
        }
        *///? }

        for (int i = 1; i < mips.length; i++) {
            mips[i].close();
        }

        this.byMipLevel = new NativeImage[]{mips[0]};
    }
}